@pytest.fixture(scope="module")
def psb_tracking_setup(psb_model_dir: Path):
    """PSB ring-3 AC-dipole tracking setup, keyed by ``delta_p``, built once per module.

    Returns a factory ``_get(delta_p)`` yielding a fresh
    :class:`tests.support.psb.PSBScenario` built by
    :func:`tests.psb_tracking.build_psb_tracking_setup`.

    Module-scoped so only one test file's worth of PSB tracking bundles is resident
    at a time; within a module, repeated calls for the same ``delta_p`` reuse the
    same scenario instead of re-tracking.
    """

    _cache: dict[float, PSBScenario] = {}

    def _load(delta_p: float):
        if delta_p in _cache:
            return _cache[delta_p]
        bundle = build_psb_scenario(psb_model_dir, delta_p=delta_p)
        _cache[delta_p] = bundle
        return bundle

    def _get(delta_p: float = 0.0):
        return _load(float(delta_p)).copy()

    return _get


