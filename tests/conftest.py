@pytest.fixture(scope="session", autouse=True)
def cleanup_autogenerated_lattice_files(data_dir: Path):
    """Remove MAD-NG/xsuite cache files generated during the test session."""
    sequences_dir = data_dir / "sequences"
    existing_files = {
        path.resolve()
        for suffix in _AUTOGENERATED_LATTICE_SUFFIXES
        for path in sequences_dir.glob(f"*{suffix}")
    }

    yield

    for suffix in _AUTOGENERATED_LATTICE_SUFFIXES:
        for path in sequences_dir.glob(f"*{suffix}"):
            if path.resolve() not in existing_files:
                path.unlink(missing_ok=True)


@pytest.fixture(scope="session")
def seq_b1(data_dir: Path, tmp_path_factory: pytest.TempPathFactory, worker_id: str) -> Path:
    """Return a worker-local copy of the beam-1 sequence.

    ``xtrack_tools`` stores the generated xsuite environment next to the
    sequence as ``lhcb1.json``.  A shared sequence path lets xdist workers
    concurrently write/read that cache, which can expose a partially-written
    JSON file.  Keeping the sequence and its cache in a worker-specific
    temporary directory makes the fixture safe with parallel pytest runs.
    """
    source = data_dir / "sequences" / "lhcb1.seq"
    worker_dir = tmp_path_factory.mktemp(f"lhcb1-{worker_id}")
    destination = worker_dir / source.name
    shutil.copy2(source, destination)
    return destination


