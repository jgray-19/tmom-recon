@pytest.fixture(scope="session")
def psb_tracking_setup(psb_model_dir: Path):
    """Return lazily generated PSB scenarios for the entire pytest session.

    Returns a factory ``_get(delta_p)`` yielding a fresh
    :class:`tests.support.psb.PSBScenario` built by
    :func:`tests.psb_tracking.build_psb_tracking_setup`.

    Each requested momentum condition is tracked once, then every consumer gets
    a copy of its mutable tables.  Expensive model objects remain session-owned.
    """

    _cache: OrderedDict[float, PSBScenario] = OrderedDict()

    def _load(delta_p: float):
        if delta_p not in _cache:
            _cache[delta_p] = build_psb_scenario(psb_model_dir, delta_p=delta_p)
            if len(_cache) > _PSB_TRACKING_SCENARIO_CACHE_SIZE:
                _cache.popitem(last=False)
        else:
            _cache.move_to_end(delta_p)
        return _cache[delta_p]

    def _get(delta_p: float = 0.0):
        return _load(float(delta_p)).copy()

    return _get


@pytest.fixture(scope="session")
def psb_scenarios(psb_model_dir: Path):
    """Return a session-cached factory for explicit PSB error scenarios.

    The cache key is the complete keyword scenario specification.  It keeps
    error-family tests independent while avoiding duplicate tracking when they
    assert different coordinates or reconstruction properties of one scenario.
    """
    cache: OrderedDict[tuple[tuple[str, object], ...], PSBScenario] = OrderedDict()

    def get(**kwargs) -> PSBScenario:
        key = tuple(sorted(kwargs.items()))
        if key not in cache:
            cache[key] = build_psb_scenario(psb_model_dir, **kwargs)
            if len(cache) > _PSB_TRACKING_SCENARIO_CACHE_SIZE:
                cache.popitem(last=False)
        else:
            cache.move_to_end(key)
        return cache[key].copy()

    return get


