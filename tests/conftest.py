@pytest.fixture(scope="session", autouse=True)
def cleanup_autogenerated_lattice_files(data_dir: Path):
    """Remove MAD-NG/xsuite cache files generated during the test session."""
    sequences_dir = data_dir / "sequences"
    existing_files = {
        path.resolve()
        for suffix in _AUTOGENERATED_LATTICE_SUFFIXES
        for path in sequences_dir.glob(f"*{suffix}")
    }

    yield

    for suffix in _AUTOGENERATED_LATTICE_SUFFIXES:
        for path in sequences_dir.glob(f"*{suffix}"):
            if path.resolve() not in existing_files:
                path.unlink(missing_ok=True)


